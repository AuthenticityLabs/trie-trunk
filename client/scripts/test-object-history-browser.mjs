// Synthetic demo, isolated browser storage. Also checks shared syntax preference.
import assert from 'node:assert/strict';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE??'playwright-core');
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH,headless:true});
let page;
try{
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 page=await context.newPage();page.setDefaultTimeout(15000);const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const origin=process.env.SNOOT_ORIGIN??'http://127.0.0.1:3020';
 await page.goto(origin);
 const form=page.getByRole('form',{name:'Search Events'});
 await form.getByRole('button',{name:'Pipeline',exact:true}).click();
 assert.equal(await page.evaluate(()=>localStorage.getItem('snoot.querySyntax')),'pipeline');
 await page.reload();assert.equal(await form.getByRole('button',{name:'Pipeline',exact:true}).getAttribute('aria-pressed'),'true');
 const fresh=await context.newPage();await fresh.goto(origin);
 const freshForm=fresh.getByRole('form',{name:'Search Events'});
 assert.equal(await freshForm.getByRole('button',{name:'Pipeline',exact:true}).getAttribute('aria-pressed'),'true');
 await freshForm.getByRole('button',{name:'Builder',exact:true}).click();
 await page.getByRole('combobox',{name:'Search Query'}).fill('');
 await page.waitForFunction(()=>document.querySelector('.query-syntax-tabs button:first-child')?.getAttribute('aria-pressed')==='true');
 await fresh.close();
 await form.getByRole('button',{name:'Cache: All Caches',exact:true}).click();
 for(const name of ['demo','payment','transactions.v1'])await form.getByRole('option',{name,exact:true}).click();
 await page.getByRole('combobox',{name:'Search Query'}).fill('events.query().where(access, ==, write)');
 await form.getByLabel('Time Window',{exact:true}).selectOption('43200');
 await form.getByRole('button',{name:'Search',exact:true}).click();
 const link=page.locator('.paged-results .object-history-link').first();await link.waitFor();
 const id=await link.textContent(),first=await page.locator('.paged-results .event-summary').first().getAttribute('id');
 const loaded=await page.locator('.paged-results .event-summary').count();
 assert.ok(id);assert.notEqual(first,'event-'+id);
 assert.equal(await link.locator('..').getByRole('button',{name:'Add Indicator for id',exact:true}).count(),1);
 await link.click();
 const dialog=page.getByRole('dialog',{name:'Object History',exact:true});await dialog.waitFor();
 await page.waitForFunction(()=>document.querySelector('.history-modal [role="status"]')?.textContent==='Complete');
 assert.match(await dialog.locator('.inspection-source').textContent(),new RegExp(` · ${id}$`));
 const records=dialog.locator('.history-entry');assert.ok(await records.count()>0);
 assert.equal(await dialog.locator('.history-entry.latest .history-panel').count(),1,'latest retained revision stays expanded');
 const toggle=records.first().locator('.history-toggle');await toggle.click();
 assert.equal(await toggle.getAttribute('aria-expanded'),'true');
 assert.ok(await records.first().locator('.history-diff-row').count()>0);
 assert.match(await toggle.getAttribute('aria-label'),/Revision/);
 const headers=await records.first().locator('.history-diff-row strong').allTextContents();
 assert.ok(!headers.includes('event_id')&&!headers.includes('id')&&!headers.includes('revision_id'));
 if(await records.count()>1){
  await toggle.press('ArrowRight');assert.equal(await records.nth(1).locator('.history-toggle').evaluate(el=>el===document.activeElement),true);
  await page.keyboard.press('Enter');assert.equal(await dialog.locator('.history-toggle[aria-expanded="true"]').count(),2);
 }
 const paired=await dialog.locator('.history-entry.expanded').evaluateAll(rows=>rows.map(r=>({x:r.getBoundingClientRect().x,y:r.getBoundingClientRect().y})));
 assert.equal(paired.length,2);assert.ok(Math.abs(paired[0].y-paired[1].y)<2);assert.ok(paired[1].x>paired[0].x);
 await page.screenshot({path:'/tmp/snoot-object-history-rails.png'});
 await page.keyboard.press('Escape');await dialog.waitFor({state:'hidden'});
 assert.equal(await link.evaluate(el=>document.activeElement===el),true,'closing restores focus to the ID');
 assert.equal(await page.locator('.paged-results .event-summary').first().getAttribute('id'),first);
 assert.ok(await page.locator('.paged-results .event-summary').count()>=loaded);
 // Standalone history retains its own query and accordion state across refresh.
 const nav=page.getByRole('complementary',{name:'Main Navigation'});
 await nav.locator('button[title="Collections"]').click();
 const history=page.getByRole('form',{name:'Object History',exact:true});await history.waitFor();
 assert.equal(await history.getByLabel('Object ID',{exact:true}).inputValue(),'','modal must not replace the standalone history draft');
 await history.getByLabel('History Resource').selectOption('demo/payment/transactions.v1/write');
 await history.getByLabel('Object ID',{exact:true}).fill(id);
 await history.getByLabel('History from UTC').fill('1970-01-01T00:00');
 await history.getByRole('button',{name:'Load History',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('[aria-label="Object History results"] [role="status"]')?.textContent==='Complete');
 await page.locator('.history-toggle').first().click();
 await history.getByLabel('Object ID',{exact:true}).fill('unsubmitted-id');
 await page.evaluate(()=>window.dispatchEvent(new Event('pagehide')));
 await page.reload();
 await page.waitForFunction(()=>document.querySelector('[aria-label="Object History results"] [role="status"]')?.textContent==='Complete');
 assert.equal(await history.getByLabel('Object ID',{exact:true}).inputValue(),'unsubmitted-id');
 assert.equal(await page.locator('.history-toggle[aria-expanded="true"]').count(),2);
 await nav.locator('button[title="Search"]').click();await link.waitFor();
 await link.click();await dialog.waitFor();
 await page.waitForFunction(()=>document.querySelector('.history-modal [role="status"]')?.textContent==='Complete');
 await page.setViewportSize({width:390,height:844});await dialog.locator('.history-toggle').first().click();
 assert.equal(await dialog.evaluate(el=>el.scrollWidth<=el.clientWidth),true,'history modal fits a narrow screen');
 await page.screenshot({path:'/tmp/snoot-object-history-rails-mobile.png'});
 await dialog.getByRole('button',{name:'Close Object History',exact:true}).click();
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({objectId:id,modal:true,accordion:true,keyboard:true,searchPreserved:true,historyRefreshPreserved:true,sharedSyntaxPreference:true,mobile:true}));
}catch(error){console.error(await page?.locator('body').innerText());throw error;}finally{await browser.close();}
